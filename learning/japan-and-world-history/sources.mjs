export function sourcesFor(event) {
  const entry = sourcesByJapanDate[event.jpDate];
  if (!entry) throw new Error(`history source missing: ${event.jpDate}`);
  const resolve = citation => ({...citation, label: references[citation.ref]?.[0], url: references[citation.ref]?.[1]});
  return { japan: entry.japan.map(resolve), world: entry.world.map(resolve) };
}
